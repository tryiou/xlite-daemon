package io.xlite.daemon.app.util;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.subgraph.orchid.encoders.Hex;

import org.bitcoinj.core.Coin;
import org.bitcoinj.core.ECKey;
import org.bitcoinj.core.NetworkParameters;
import org.bitcoinj.core.Sha256Hash;
import org.bitcoinj.core.Transaction;
import org.bitcoinj.core.TransactionInput;
import org.bitcoinj.core.TransactionOutPoint;
import org.bitcoinj.core.TransactionOutput;
import org.bitcoinj.params.MainNetParams;
import org.bitcoinj.script.Script;
import org.junit.jupiter.api.Test;

import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.List;

/**
 * The Bitcoin Cash signature hash against BCHN's own recorded vectors.
 *
 * <p>The fixture is a subset of {@code src/test/data/sighash.json} from Bitcoin Cash Node v29.1.0
 * (the "signature_hash (regular)" column, which is the hash computed with
 * SCRIPT_ENABLE_SIGHASH_FORKID). Those vectors are generated by the node's own {@code
 * SignatureHash}, so a disagreement is a real defect rather than a second transcription of the
 * layout. The spent value in those vectors is zero, as the generator constructs the context with
 * {@code CTxOut{Amount::zero(), scriptCode}}.
 */
class ForkIdSignerTest {

    private static final NetworkParameters PARAMS = MainNetParams.get();
    private static final int SIGHASH_ALL_FORKID = 0x41;

    @Test
    void matchesBchnRecordedVectors() throws Exception {
        JsonArray vectors = vectors();
        assertTrue(vectors.size() >= 4, "expected the pinned vector set, got " + vectors.size());
        for (JsonElement element : vectors) {
            JsonObject vector = element.getAsJsonObject();
            Transaction transaction =
                    new Transaction(PARAMS, Hex.decode(vector.get("rawTransaction").getAsString()));
            Script scriptCode = new Script(Hex.decode(vector.get("script").getAsString()));
            int inputIndex = vector.get("inputIndex").getAsInt();
            int hashType = (int) vector.get("hashType").getAsLong();
            String expected = vector.get("expectedSighash").getAsString();

            Sha256Hash actual =
                    ForkIdSigner.sighash(
                            transaction,
                            scriptCode,
                            new ForkIdSigner.SighashRequest(inputIndex, Coin.ZERO, hashType));

            assertEquals(
                    Sha256Hash.wrapReversed(Hex.decode(expected)),
                    actual,
                    "vector hashType=0x" + Integer.toHexString(hashType) + " input=" + inputIndex);
        }
    }

    @Test
    void refusesOneWithoutTheForkFlag() {
        Transaction transaction = oneInputOneOutput();
        assertThrows(
                IllegalArgumentException.class,
                () ->
                        ForkIdSigner.sighash(
                                transaction,
                                p2pkh(),
                                new ForkIdSigner.SighashRequest(0, Coin.CENT, 0x01)));
    }

    @Test
    void refusesNoneAndSingle() {
        Transaction transaction = oneInputOneOutput();
        assertThrows(
                IllegalArgumentException.class,
                () ->
                        ForkIdSigner.sighash(
                                transaction,
                                p2pkh(),
                                new ForkIdSigner.SighashRequest(0, Coin.CENT, 0x42)));
        assertThrows(
                IllegalArgumentException.class,
                () ->
                        ForkIdSigner.sighash(
                                transaction,
                                p2pkh(),
                                new ForkIdSigner.SighashRequest(0, Coin.CENT, 0x43)));
    }

    @Test
    void refusesAnyoneCanPay() {
        Transaction transaction = oneInputOneOutput();
        assertThrows(
                IllegalArgumentException.class,
                () ->
                        ForkIdSigner.sighash(
                                transaction,
                                p2pkh(),
                                new ForkIdSigner.SighashRequest(0, Coin.CENT, 0xc1)));
    }

    @Test
    void refusesAnInputIndexOutsideTheTransaction() {
        Transaction transaction = oneInputOneOutput();
        assertThrows(
                IllegalArgumentException.class,
                () ->
                        ForkIdSigner.sighash(
                                transaction,
                                p2pkh(),
                                new ForkIdSigner.SighashRequest(1, Coin.CENT, SIGHASH_ALL_FORKID)));
    }

    @Test
    void refusesMismatchedInputLists() {
        Transaction transaction = oneInputOneOutput();
        ForkIdSigner.InputsToSign inputs =
                new ForkIdSigner.InputsToSign(
                        List.of(new ECKey()),
                        List.of(new TransactionOutPoint(PARAMS, 0, Sha256Hash.ZERO_HASH)),
                        List.of(p2pkh()),
                        List.of());
        assertThrows(
                IllegalArgumentException.class,
                () -> ForkIdSigner.addSignedInputs(PARAMS, transaction, inputs));
    }

    private static Transaction oneInputOneOutput() {
        Transaction transaction = new Transaction(PARAMS);
        transaction.addInput(
                new TransactionInput(
                        PARAMS,
                        transaction,
                        new byte[0],
                        new TransactionOutPoint(PARAMS, 0, Sha256Hash.ZERO_HASH)));
        transaction.addOutput(
                new TransactionOutput(PARAMS, transaction, Coin.CENT, p2pkh().getProgram()));
        return transaction;
    }

    private static Script p2pkh() {
        return new Script(Hex.decode("76a914000000000000000000000000000000000000000088ac"));
    }

    private static JsonArray vectors() throws Exception {
        try (InputStream in =
                ForkIdSignerTest.class.getResourceAsStream("/sighash/bch-forkid-vectors.json")) {
            if (in == null) {
                throw new IllegalStateException("missing sighash vector fixture");
            }
            return JsonParser.parseString(new String(in.readAllBytes(), StandardCharsets.UTF_8))
                    .getAsJsonArray();
        }
    }
}
